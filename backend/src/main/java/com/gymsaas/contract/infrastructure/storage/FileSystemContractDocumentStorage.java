package com.gymsaas.contract.infrastructure.storage;

import com.gymsaas.contract.domain.ContractDocumentStorage;
import com.gymsaas.contract.domain.StoredDocument;
import com.gymsaas.shared.application.ApiException;
import com.gymsaas.shared.domain.Sha256;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.FileAlreadyExistsException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.regex.Pattern;

/**
 * Stores contract PDFs under a base directory (a Docker volume in compose).
 * Keys are generated by the application ({tenant}/{membership}/{contract}-vN.pdf)
 * and validated against a strict pattern; paths can never escape the base
 * directory and existing files are never overwritten.
 */
@Component
public class FileSystemContractDocumentStorage implements ContractDocumentStorage {

    private static final String UUID_PATTERN = "[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}";
    private static final Pattern KEY = Pattern.compile(
            "^" + UUID_PATTERN + "/" + UUID_PATTERN + "/" + UUID_PATTERN + "-v[0-9]{1,6}\\.pdf$");

    private final Path baseDir;

    public FileSystemContractDocumentStorage(
            @Value("${app.storage.contracts.base-dir:./data/contracts}") String baseDir) {
        this.baseDir = Path.of(baseDir).toAbsolutePath().normalize();
    }

    @Override
    public StoredDocument store(String storageKey, byte[] content, String contentType) {
        Path target = resolve(storageKey);
        try {
            Files.createDirectories(target.getParent());
            if (Files.exists(target)) {
                throw new FileAlreadyExistsException(storageKey);
            }
            Path temp = Files.createTempFile(target.getParent(), ".upload-", ".tmp");
            try {
                Files.write(temp, content);
                Files.move(temp, target, StandardCopyOption.ATOMIC_MOVE);
            } finally {
                Files.deleteIfExists(temp);
            }
        } catch (IOException exception) {
            throw new UncheckedIOException("Could not store contract document", exception);
        }
        return new StoredDocument(storageKey, Sha256.hex(content), content.length, contentType);
    }

    @Override
    public byte[] load(String storageKey) {
        try {
            return Files.readAllBytes(resolve(storageKey));
        } catch (NoSuchFileException exception) {
            throw ApiException.notFound("DOCUMENT_NOT_FOUND", "Arquivo do contrato não encontrado no armazenamento.");
        } catch (IOException exception) {
            throw new UncheckedIOException("Could not read contract document", exception);
        }
    }

    private Path resolve(String storageKey) {
        if (storageKey == null || !KEY.matcher(storageKey).matches()) {
            throw new IllegalArgumentException("Invalid contract storage key");
        }
        Path resolved = baseDir.resolve(storageKey).normalize();
        if (!resolved.startsWith(baseDir)) {
            throw new IllegalArgumentException("Storage key escapes base directory");
        }
        return resolved;
    }
}
